const { chromium } = require('playwright');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');

async function run() {
  const root = path.resolve(__dirname, '..');
  const core = await import(pathToFileURL(path.join(root, 'src/domain/core.js')));
  const { builtInCatalog: catalog } = await import(pathToFileURL(path.join(root, 'src/data/catalog.js')));
  const { addSampleOrders } = await import(pathToFileURL(path.join(root, 'src/data/samples.js')));
  const key = 'gunters-forge-v54-demo';
  const state = addSampleOrders(catalog, core.placeCartOrder(catalog, { ...core.makeState(), cart: { 'sword-short': 1 } },
    { name: 'Orb Buyer', email: 'orb@example.com' }, 'GF-0001', '2026-10-20T10:00:00.000Z').state);
  const server = http.createServer((req, res) => {
    const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
    if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
    fs.readFile(file, (error, data) => {
      if (error) { res.writeHead(404).end(); return; }
      res.setHeader('Content-Type', ({ '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.webp': 'image/webp' })[path.extname(file)] || 'application/octet-stream');
      res.end(data);
    });
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  let browser;
  const screenshots = path.join(root, 'previews', 'v514');
  fs.mkdirSync(screenshots, { recursive: true });
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
    for (const entry of ['index.html', 'dist/Birdforge_V6_0_Standalone.html']) {
      const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', (error) => errors.push(error.message));
      const url = `http://127.0.0.1:${server.address().port}/${entry}`;
      const getState = () => page.evaluate((key) => JSON.parse(localStorage.getItem(key)), key);
      const go = (view) => page.locator(`.mobile-nav [data-view="${view}"]:visible`).click();
      const change = (status, id = 'GF-0001') => page.locator(`.admin-order[data-order="${id}"] select[data-action="status"]`).selectOption(status);
      await page.goto(url);
      await page.evaluate(({ key, state }) => localStorage.setItem(key, JSON.stringify(state)), { key, state });
      await page.reload();
      assert.equal(await page.locator('#orb-launcher').isVisible(), true);
      await go('admin');
      await change('Processing', 'GF-0002');
      await go('shop');
      assert.equal(await page.locator('.orb-banner').count(), 0);
      await go('admin');
      await change('Processing');
      await change('Delivering');
      await go('shop');
      assert.equal(await page.locator('.orb-banner').count(), 2);
      assert.ok((await getState()).orb.messages.every((m) => m.shown && !m.read));
      const firstBounds = await page.locator('.orb-banner').first().boundingBox();
      assert.ok(firstBounds.width >= 360 && firstBounds.height >= 84);
      await page.screenshot({ path: path.join(screenshots, 'two-notifications-mobile.png') });
      await go('repairs');
      assert.equal(await page.locator('.orb-banner').count(), 2);
      await page.locator('.orb-banner').first().click();
      assert.equal(await page.locator('.order-card.orb-order-highlight[data-order="GF-0001"]').count(), 1);
      await page.locator('#orb-launcher').click();
      assert.ok((await getState()).orb.messages.every((m) => m.read));
      assert.equal(await page.locator('.orb-unread').isVisible(), false);
      await page.locator('#orb-dialog select[name="orderId"]').selectOption('GF-0001');
      await page.locator('#orb-dialog textarea').fill('Can I collect my sword tomorrow?');
      await page.locator('[data-orb-action="close"]').click();
      await go('shop');
      await page.locator('#orb-launcher').click();
      assert.equal(await page.locator('#orb-dialog textarea').inputValue(), 'Can I collect my sword tomorrow?');
      await page.locator('#orb-dialog button[type="submit"]').click();
      assert.equal((await getState()).orb.messages.at(-1).kind, 'customer');
      assert.equal((await getState()).orb.messages.at(-1).read, false);
      await page.locator('[data-orb-action="close"]').click();
      await go('admin');
      assert.match(await page.locator('[data-id="messages"]').innerText(), /Messages \(1\)/);
      await page.locator('[data-id="messages"]').click();
      await page.locator('#forge-messages textarea').fill('Yes, your sword will be waiting at the forge.');
      await page.locator('#forge-messages button[type="submit"]').click();
      assert.equal((await getState()).orb.messages.find((m) => m.kind === 'customer').read, true);
      await go('shop');
      assert.equal(await page.locator('.orb-banner').innerText(), 'Gunter sent you a message.');
      await page.locator('.orb-banner').click();
      assert.equal(await page.locator('#orb-dialog').isVisible(), true);
      assert.ok((await getState()).orb.messages.filter((m) => m.kind !== 'customer').every((m) => m.read));
      await page.screenshot({ path: path.join(screenshots, 'orb-chat-mobile.png') });
      await page.locator('[data-orb-action="close"]').click();
      await page.reload();
      assert.equal(await page.locator('.orb-banner').count(), 0);
      assert.equal((await getState()).orb.messages.length, 4);
      await go('admin');
      await page.locator('[data-id="messages"]').click();
      await page.screenshot({ path: path.join(screenshots, 'forge-messages-mobile.png') });
      await page.setViewportSize({ width: 1350, height: 900 });
      await page.screenshot({ path: path.join(screenshots, 'forge-messages-desktop.png') });
      await page.setViewportSize({ width: 390, height: 844 });
      await page.evaluate(({ key, state }) => localStorage.setItem(key, JSON.stringify(state)), { key, state });
      await page.reload();
      await go('admin');
      for (const status of ['Processing', 'Delivering', 'Delivered']) await change(status);
      await go('shop');
      assert.equal(await page.locator('.orb-banner').count(), 2);
      assert.equal(await page.locator('.orb-banner').last().innerText(), 'And 2 more notifications.');
      await page.screenshot({ path: path.join(screenshots, 'grouped-notifications-mobile.png') });
      await page.locator('.orb-banner').first().click();
      assert.equal(await page.locator('#orb-dialog').isVisible(), true);
      assert.ok((await getState()).orb.messages.every((m) => m.read));
      assert.equal(await page.locator('.orb-notification').count(), 3);
      await page.keyboard.press('Escape');
      await go('admin');
      await page.locator('#show-delivered').check();
      await change('Processing');
      await go('shop');
      assert.equal(await page.locator('.orb-banner').count(), 1);
      await page.waitForTimeout(1800);
      await go('repairs');
      await page.waitForTimeout(2500);
      assert.equal(await page.locator('.orb-banner').count(), 0);
      assert.equal(await page.locator('.orb-unread').isVisible(), true);
      await page.reload();
      assert.equal(await page.locator('.orb-banner').count(), 0);
      await page.setViewportSize({ width: 360, height: 640 });
      await page.locator('#orb-launcher').click();
      await page.locator('#orb-dialog textarea').fill('<img src=x onerror=alert(1)>');
      await page.locator('#orb-dialog button[type="submit"]').click();
      assert.equal(await page.locator('#orb-dialog .orb-customer .orb-bubble img').count(), 0);
      const bounds = await page.locator('#orb-dialog').boundingBox();
      assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 360 && bounds.y + bounds.height <= 640);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: path.join(screenshots, 'orb-chat-small-mobile.png') });
      assert.deepEqual(errors, []);
      console.log(`PASS ${entry}: banners, navigation, read-all, conversations, replies, persistence, timing, mobile layout`);
      await context.close();
    }
    const offline = await browser.newPage({ viewport: { width: 390, height: 844 } });
    await offline.goto(pathToFileURL(path.join(root, 'dist/Birdforge_V6_0_Standalone.html')).href);
    await offline.locator('#orb-launcher').click();
    assert.equal(await offline.locator('#orb-dialog').isVisible(), true);
    console.log('PASS standalone file:// boot');
  } finally { await browser?.close(); server.close(); }
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
